/**
 * 应用内「更新日志」数据烘焙：.github/release-notes/v*.md → src/generated/releaseNotes.js
 *
 * 为什么要烘焙：桌面 renderer 没有 Node fs、CEP 面板也不能假定发布目录里有源码文件，
 * 两端运行时都读不到 .github/ 下的编辑源。把 Markdown 原文烘焙成可 import 的纯数据，
 * 两端共用同一份，格式化仍走 src/util/updateCheck.js 的 formatReleaseNotes（单一逻辑源）。
 *
 * 用法：node scripts/bake-release-notes.js
 * 发版：版本号 bump / 新增 vX.Y.Z.md 后必须重跑；doctor:version 会校验一致性。
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const SRC_DIR = path.join(ROOT, '.github', 'release-notes')
const OUT_FILE = path.join(ROOT, 'src', 'generated', 'releaseNotes.js')
const FILE_RE = /^v(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)\.md$/

function splitSemver (v) {
  var s = String(v).replace(/^v/i, '')
  var plus = s.indexOf('+')
  if (plus >= 0) { s = s.slice(0, plus) }
  var dash = s.indexOf('-')
  var core = dash >= 0 ? s.slice(0, dash) : s
  return core.split('.').map(function (n) { return parseInt(n, 10) || 0 })
}

function compareVersion (a, b) {
  var x = splitSemver(a)
  var y = splitSemver(b)
  for (var i = 0; i < 3; i++) {
    if ((x[i] || 0) !== (y[i] || 0)) { return (x[i] || 0) - (y[i] || 0) }
  }
  return 0
}

function main () {
  var files = fs.readdirSync(SRC_DIR)
  var versions = []
  files.forEach(function (name) {
    var m = name.match(FILE_RE)
    if (m) { versions.push(m[1]) }
  })
  versions.sort(compareVersion).reverse()

  var notes = {}
  var notesEn = {}
  var enRe = /<!--\s*RELEASE_EN_START\s*-->([\s\S]*?)<!--\s*RELEASE_EN_END\s*-->/
  versions.forEach(function (v) {
    var raw = fs.readFileSync(path.join(SRC_DIR, 'v' + v + '.md'), 'utf8')
    var m = raw.match(enRe)
    notes[v] = raw
    notesEn[v] = m ? m[1].trim() : raw
  })

  var body = [
    '// AUTO-GENERATED by scripts/bake-release-notes.js — DO NOT EDIT.',
    '// 编辑源：.github/release-notes/v<版本>.md；改完重跑 node scripts/bake-release-notes.js',
    '',
    'export const RELEASE_NOTES = ' + JSON.stringify(notes, null, 2),
    '',
    'export const RELEASE_NOTES_EN = ' + JSON.stringify(notesEn, null, 2),
    '',
    'export const RELEASE_VERSIONS = ' + JSON.stringify(versions),
    ''
  ].join('\n')

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, body, 'utf8')
  console.log('wrote', path.relative(ROOT, OUT_FILE), 'versions=', versions.length)
}

main()
